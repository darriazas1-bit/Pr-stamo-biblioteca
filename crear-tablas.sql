-- Script de creación de la base de datos y tablas
CREATE DATABASE IF NOT EXISTS mi_proyecto;
USE mi_proyecto;

-- Tabla AUTOR
CREATE TABLE IF NOT EXISTS AUTOR (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(255) NOT NULL
);

-- Tabla LECTORES
CREATE TABLE IF NOT EXISTS LECTORES (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    CODIGO VARCHAR(50) NOT NULL,
    NOMBRE VARCHAR(255) NOT NULL,
    CORREO VARCHAR(255) NOT NULL,
    TELEFONO VARCHAR(50) NOT NULL
);

-- Tabla LIBROS
CREATE TABLE IF NOT EXISTS LIBROS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    CODIGO VARCHAR(50) NOT NULL,
    TITULO VARCHAR(255) NOT NULL,
    AUTOR INT,
    EJEMPLARES INT NOT NULL,
    CHECK (EJEMPLARES >= 0),
    FOREIGN KEY (AUTOR) REFERENCES AUTOR(ID) ON DELETE SET NULL
);

-- Tabla PRESTAMOS
CREATE TABLE IF NOT EXISTS PRESTAMOS (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    LECTORID INT NOT NULL,
    LIBROID INT NOT NULL,
    FECHAPRESTAMO DATE NOT NULL,
    FECHADEV DATE NOT NULL,
    FECHALIMITE DATE NOT NULL,
    CHECK (FECHALIMITE >= FECHAPRESTAMO),
    FOREIGN KEY (LECTORID) REFERENCES LECTORES(ID) ON DELETE CASCADE,
    FOREIGN KEY (LIBROID) REFERENCES LIBROS(ID) ON DELETE CASCADE
);

-- Índice
CREATE INDEX IX_PRESTAMOS_LECTORID ON PRESTAMOS(LECTORID);